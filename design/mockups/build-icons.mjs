// Collects every Lucide icon name used by the mockups and writes src/icons.js
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
const ICON_DIR = "node_modules/lucide-static/icons";
const files = readdirSync("src").filter((f) => f.endsWith(".html") || f === "common.js");
const names = new Set();
for (const f of files) {
  const text = readFileSync(`src/${f}`, "utf8");
  for (const m of text.matchAll(/data-icon="([a-z0-9-]+)"/g)) names.add(m[1]);
  for (const m of text.matchAll(/["']([a-z0-9-]+)["']/g)) if (existsSync(`${ICON_DIR}/${m[1]}.svg`)) names.add(m[1]);
}
const icons = {};
for (const n of [...names].sort()) {
  const p = `${ICON_DIR}/${n}.svg`;
  if (!existsSync(p)) { console.warn("missing icon:", n); continue; }
  icons[n] = readFileSync(p, "utf8").replace(/<!--.*?-->/gs, "").replace(/\s*class="[^"]*"/, "").replace(/\s+/g, " ").trim();
}
writeFileSync("src/icons.js", `// Generated by build-icons.mjs from lucide-static (ISC licence)\nwindow.ICONS = ${JSON.stringify(icons)};\n`);
console.log(`icons.js: ${Object.keys(icons).length} icons`);
